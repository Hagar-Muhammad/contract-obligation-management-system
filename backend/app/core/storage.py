"""Where original document files live (docs/architecture.md: StorageBackend; FR-DOC-02, NFR-SEC-05).

Files are write-once: a key is written exactly once and never overwritten. Keys are opaque and generated by the
application, never taken from user input, and files are never served from a public path.
"""

import shutil
import uuid
from collections.abc import Iterator
from datetime import UTC, datetime
from pathlib import Path
from typing import BinaryIO, Protocol

from app.core.config import get_settings

CHUNK_SIZE = 64 * 1024


class StorageBackend(Protocol):
    def new_key(self) -> str: ...

    def save(self, key: str, source: BinaryIO) -> None:
        """Store `source` under `key`. Fails if the key already exists (write-once)."""

    def open(self, key: str) -> BinaryIO: ...

    def delete(self, key: str) -> None:
        """Only for undoing a save whose database record was never committed."""


class LocalStorage:
    """Files on a local disk path. Suitable for development and single-server installs; S3 can replace it later."""

    def __init__(self, root: Path) -> None:
        self.root = root.resolve()

    def new_key(self) -> str:
        now = datetime.now(UTC)
        return f"{now:%Y/%m}/{uuid.uuid4().hex}"

    def _path(self, key: str) -> Path:
        path = (self.root / key).resolve()
        if not path.is_relative_to(self.root):  # defence in depth: keys are ours, but never escape the root
            raise ValueError("Invalid storage key.")
        return path

    def save(self, key: str, source: BinaryIO) -> None:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open("xb") as target:  # "x": refuse to overwrite an existing original
            shutil.copyfileobj(source, target, CHUNK_SIZE)

    def open(self, key: str) -> BinaryIO:
        return self._path(key).open("rb")

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)


def get_storage() -> StorageBackend:
    """FastAPI dependency; tests override it with a temporary directory."""
    return LocalStorage(Path(get_settings().storage_dir))


def iter_file(handle: BinaryIO) -> Iterator[bytes]:
    """Stream a stored file in chunks, closing it at the end."""
    with handle:
        while chunk := handle.read(CHUNK_SIZE):
            yield chunk
